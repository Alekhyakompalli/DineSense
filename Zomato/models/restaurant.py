"""
models/restaurant.py
─────────────────────
Dataclass definitions for core domain models:
- Restaurant: In-memory representation of a cleaned restaurant record.
- UserPreferences: Structured representation of user preferences.
- Recommendation: Structured recommendation generated by the LLM.
"""

from dataclasses import dataclass, field


@dataclass
class Restaurant:
    """Represents a clean, preprocessed restaurant entity."""
    name: str
    location: str
    cuisines: str
    cost: int  # Approx cost for two (INR)
    budget: str  # "low" | "medium" | "high"
    rating: float  # 0.0 - 5.0


@dataclass
class UserPreferences:
    """Represents user input preferences collected from the UI or API."""
    location: str
    budget: str  # "low" | "medium" | "high"
    cuisines: list[str] = field(default_factory=list)  # e.g. ["Italian", "Chinese"]
    min_rating: float = 0.0  # e.g. 4.0
    extras: str = ""  # Free-text additional notes


@dataclass
class Recommendation:
    """Represents an LLM-ranked recommendation with explanation."""
    rank: int
    name: str
    cuisine: str
    rating: float
    cost: int
    explanation: str
